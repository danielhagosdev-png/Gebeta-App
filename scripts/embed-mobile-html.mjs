// Reads dist-mobile/index.html and writes it into mobile/webAppHtml.ts as a string.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const source = 'dist-mobile/index.html';
const target = 'mobile/webAppHtml.ts';

const html = readFileSync(source, 'utf8');
if (!html.includes('<script')) {
  throw new Error(`${source} has no script tag. Run "npm run build:mobile" first.`);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/embed-mobile-html.mjs. Do not edit by hand.\nexport const WEB_APP_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Embedded ${(html.length / 1024).toFixed(0)} KB into ${target}`);
